/**
 * Writes the data guide from the self-contained catalog specs (run `npm run catalog` first; it runs this after):
 *
 * - catalog/guide.html: per chart, the table it needs, the data drawing it now, when to use it and not,
 *   and every other chart the same data makes, with an assessment and a live preview.
 * - catalog/guide/<type>.md: the same for one chart as Markdown, with all its rows, to hand to another model or system.
 * - catalog/guide/all.json: everything but the rows, for code.
 * - docs/chart-guide.md: the overview: which chart for which job, and the best switches per chart.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { blockTypes, chartGuide, chartsFor, dataContract, describeChart, guideMarkdown, PURPOSES, switchOptions } from "../src/core/index.ts";
import type { ChartSwitch, Purpose, Row, WidgetSpec } from "../src/core/index.ts";

const root = (path: string) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const escape = (text: unknown) => String(text ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const show = (value: unknown) => (value === null || value === undefined ? "" : typeof value === "object" ? JSON.stringify(value) : String(value));

/** Rows shown in the page before "Show all". */
const PAGE_ROWS = 8;
const STRENGTH = { 3: "best", 2: "good", 1: "possible" } as const;
const VERDICT_WORDS: Record<string, string> = { better: "Better", same: "Same job", "trade-off": "Trade-off", different: "Different question", worse: "Worse" };
const MARK: Record<string, string> = { better: "▲", same: "●", "trade-off": "◆", different: "◇", worse: "▽" };

interface Built {
  type: string;
  spec: WidgetSpec;
  rows: Row[];
  switches: ChartSwitch[];
}

const charts: Built[] = [];
for (const type of blockTypes("view")) {
  const spec = JSON.parse(await readFile(root(`catalog/${type}.json`), "utf8")) as WidgetSpec;
  const rows = spec.data.rows as Row[];
  charts.push({ type, spec, rows, switches: switchOptions(spec, rows) });
}

// One Markdown file per chart, and the JSON for code.
await mkdir(root("catalog/guide"), { recursive: true });
for (const chart of charts) await writeFile(root(`catalog/guide/${chart.type}.md`), guideMarkdown(chart.spec, chart.rows));
const json = {
  purposes: PURPOSES,
  charts: charts.map(({ type, spec, rows, switches }) => {
    const { columns, ...contract } = dataContract(spec, rows);
    return {
      type,
      summary: describeChart(type).summary,
      spec: `${type}.json`,
      markdown: `guide/${type}.md`,
      guide: chartGuide(type),
      contract: { ...contract, columns },
      switches: switches.map(({ from: _from, ...rest }) => rest),
    };
  }),
};
await writeFile(root("catalog/guide/all.json"), `${JSON.stringify(json)}\n`);

// The overview in docs.
const purposeRows = (Object.keys(PURPOSES) as Purpose[]).map((purpose) => {
  const list = chartsFor(purpose);
  const names = (score: number) => list.filter((c) => c.score === score).map((c) => `[\`${c.type}\`](#${c.type})`).join(", ");
  return `| ${PURPOSES[purpose]} | ${names(3)} | ${names(2)} |`;
});
const doc = [
  "# Chart guide",
  "",
  "Generated by `npm run catalog` from `src/core/guide.ts` and the catalog specs. Do not edit by hand.",
  "",
  "For each chart: the jobs it does well and badly, the table it needs, and which other charts the same data makes, with an assessment of each switch. The full entry per chart, with the example data in full as a table and as CSV, is in [catalog/guide/](../catalog/guide/) (one Markdown file per chart, ready to hand to another model); the same as JSON is [catalog/guide/all.json](../catalog/guide/all.json); the page is [catalog/guide.html](../catalog/guide.html).",
  "",
  "In code: `dataContract(spec, rows)`, `switchChart(spec, to, rows)`, `switchOptions(spec, rows)` and `guideMarkdown(spec, rows)` work on any data. Over MCP: `fft_chart_guide` and `fft_switch_chart`.",
  "",
  "## Which chart for which job",
  "",
  "| Job | Best | Good |",
  "| --- | --- | --- |",
  ...purposeRows,
  "",
  "## How switches are judged",
  "",
  "Each switch redraws the example's data as another chart, filling the new chart's options from the columns the current one draws, then:",
  "",
  "- **Fit**: `fits`; `stretch` (it draws, but something is off, such as too many rows or text where dates are expected); or `no` (a column it needs is missing, or the data does not mean what the chart's marks mean, such as open, high, low and close for a candlestick).",
  "- **Verdict**, on the current chart's main job: `better` keeps it and adds another; `same` keeps it; `trade-off` gains a job but does the main one less clearly; `different` answers another question; `worse` loses ground with nothing gained. A gain only counts when the data suits the new chart.",
  "",
];
for (const { type, spec, rows, switches } of charts) {
  const guide = chartGuide(type);
  const contract = dataContract(spec, rows);
  if (!guide) continue;
  const useful = switches.filter((s) => s.fit !== "no" && s.verdict !== "worse");
  doc.push(`## ${type}`, "", describeChart(type).summary, "");
  doc.push(`**Jobs**: ${(Object.entries(guide.purposes) as [Purpose, 1 | 2 | 3][]).sort((a, b) => b[1] - a[1]).map(([p, s]) => `${PURPOSES[p].toLowerCase()} (${STRENGTH[s]})`).join(", ")}.`, "");
  doc.push(`**Best for**: ${guide.bestFor.join("; ")}.`, "", `**Least useful for**: ${guide.avoidFor.join("; ")}.`, "");
  doc.push(`**One row is**: ${contract.rowMeans} **Built**: ${contract.build}`, "");
  doc.push(`**Needs**: ${contract.needs.filter((n) => n.required).map((n) => `\`${n.option}\` (${n.holds}${n.many ? ", one or more" : ""})`).join(", ") || "any rows"}. Example: ${rows.length} rows of ${contract.columns.map((c) => `\`${c.name}\``).join(", ")}. [Full entry with the data](../catalog/guide/${type}.md).`, "");
  if (useful.length) {
    doc.push("| Switch to | Fit | Verdict | Assessment |", "| --- | --- | --- | --- |");
    for (const s of useful) doc.push(`| \`${s.to}\` | ${s.fit} | ${s.verdict} | ${s.assessment.replace(/\|/g, "\\|")}${s.caveats.length ? ` *${s.caveats.join(" ").replace(/\|/g, "\\|")}*` : ""} |`);
    doc.push("");
  }
}
await writeFile(root("docs/chart-guide.md"), doc.join("\n"));

// The page.
const types = charts.map((c) => c.type);
const cellFor = (from: Built, to: string) => {
  if (from.type === to) return `<td class="self" title="${escape(to)}"></td>`;
  const s = from.switches.find((x) => x.to === to);
  if (!s || s.fit === "no") return `<td class="no" title="${escape(`${from.type} → ${to}: not possible`)}"></td>`;
  return `<td class="v-${s.verdict}${s.fit === "stretch" ? " stretch" : ""}"><button type="button" data-from="${from.type}" data-to="${to}" title="${escape(`${from.type} → ${to}: ${VERDICT_WORDS[s.verdict ?? "worse"]}${s.fit === "stretch" ? " (stretch)" : ""}`)}" aria-label="${escape(`${from.type} as ${to}: ${VERDICT_WORDS[s.verdict ?? "worse"]}`)}">${MARK[s.verdict ?? "worse"]}</button></td>`;
};

const purposeTable = (Object.keys(PURPOSES) as Purpose[])
  .map((purpose) => {
    const list = chartsFor(purpose);
    const links = (score: number) => list.filter((c) => c.score === score).map((c) => `<a href="#c-${c.type}">${c.type}</a>`).join(" ");
    return `<tr><th scope="row">${escape(PURPOSES[purpose])}</th><td class="chips">${links(3)}</td><td class="chips">${links(2)}</td></tr>`;
  })
  .join("\n");

const views: Record<string, Record<string, unknown>> = {};
const section = ({ type, spec, rows, switches }: Built) => {
  const guide = chartGuide(type);
  const contract = dataContract(spec, rows);
  const entry = describeChart(type);
  const order = contract.columns.map((c) => c.name);
  const ok = switches.filter((s) => s.fit !== "no");
  const no = switches.filter((s) => s.fit === "no");
  views[type] = Object.fromEntries(ok.map((s) => [s.to, s.view]));
  const { min, max } = contract.rowsRead;
  return `
  <section class="chart" id="c-${type}" aria-labelledby="h-${type}">
    <header>
      <h2 id="h-${type}"><code>${type}</code></h2>
      <p class="summary">${escape(entry.summary)}</p>
      <p class="chips">${(Object.entries(guide?.purposes ?? {}) as [Purpose, 1 | 2 | 3][])
        .sort((a, b) => b[1] - a[1])
        .map(([p, s]) => `<span class="chip s${s}" title="${STRENGTH[s]}">${escape(PURPOSES[p])}</span>`)
        .join(" ")}</p>
    </header>
    <div class="top">
      <div class="live">
        <label class="as"><span>Show this data as</span>
          <select data-type="${type}">
            <option value="${type}">${type} (as made)</option>
            ${ok.map((s) => `<option value="${s.to}">${s.to}: ${escape((VERDICT_WORDS[s.verdict ?? "worse"] ?? "").toLowerCase())}${s.fit === "stretch" ? ", stretch" : ""}</option>`).join("\n            ")}
          </select>
        </label>
        <p class="said" id="said-${type}" aria-live="polite"></p>
        <fft-widget id="w-${type}" src="${type}.json" actions="info expand csv"></fft-widget>
      </div>
      <div class="uses">
        <h3>Best for</h3>
        <ul>${(guide?.bestFor ?? []).map((b) => `<li>${escape(b)}</li>`).join("")}</ul>
        <h3>Least useful for</h3>
        <ul class="avoid">${(guide?.avoidFor ?? []).map((a) => `<li>${escape(a)}</li>`).join("")}</ul>
      </div>
    </div>

    <h3>The table it needs</h3>
    <p><strong>One row is:</strong> ${escape(contract.rowMeans)} <strong>How it is built:</strong> ${escape(contract.build)}${min !== undefined || max !== undefined ? ` <strong>Reads well with</strong> ${min ?? 1} to ${max ?? "any number of"} rows.` : ""}</p>
    <div class="scroll"><table>
      <thead><tr><th scope="col">Option</th><th scope="col">Holds</th><th scope="col">Required</th><th scope="col">What it does</th></tr></thead>
      <tbody>${contract.needs.map((n) => `<tr><td><code>${n.option}</code></td><td>${n.holds}${n.many ? " (one or more)" : ""}</td><td>${n.required ? "yes" : ""}</td><td>${escape(n.description)}</td></tr>`).join("") || `<tr><td colspan="4">Any rows: every field becomes a column.</td></tr>`}</tbody>
    </table></div>

    <h3>This example's columns</h3>
    <div class="scroll"><table>
      <thead><tr><th scope="col">Column</th><th scope="col">Holds</th><th scope="col">Drawn as</th><th scope="col">Values</th></tr></thead>
      <tbody>${contract.columns
        .map((c) => `<tr${c.roles.length ? "" : ' class="unused"'}><td><code>${escape(c.name)}</code>${c.label ? ` <span class="muted">${escape(c.label)}</span>` : ""}</td><td>${c.kind}</td><td>${c.roles.length ? c.roles.map((r) => `<code>${escape(r)}</code>`).join(" ") : "not drawn"}</td><td>${c.min !== undefined ? `${escape(c.min)} to ${escape(c.max)}` : `${c.distinct} different: ${c.examples.map((e) => escape(show(e))).join(", ")}`}</td></tr>`)
        .join("")}</tbody>
    </table></div>
    ${contract.warnings.length ? `<p class="warn">${contract.warnings.map(escape).join(" ")}</p>` : ""}

    <h3>The data drawing it now <span class="muted">${rows.length} row${rows.length === 1 ? "" : "s"}</span></h3>
    <div class="scroll"><table class="data" id="d-${type}">
      <thead><tr>${order.map((c) => `<th scope="col">${escape(c)}</th>`).join("")}</tr></thead>
      <tbody>${rows
        .slice(0, PAGE_ROWS)
        .map((row) => `<tr>${order.map((c) => `<td>${escape(show(row[c]))}</td>`).join("")}</tr>`)
        .join("")}</tbody>
    </table></div>
    <p class="tools">${rows.length > PAGE_ROWS ? `<button type="button" data-all="${type}">Show all ${rows.length} rows</button>` : ""}<button type="button" data-csv="${type}">Copy as CSV</button><button type="button" data-md="${type}">Copy for an LLM</button><a href="guide/${type}.md">Open as Markdown</a><a href="${type}.json">Spec (JSON)</a></p>

    <h3>The same data as another chart</h3>
    <div class="scroll"><table class="switches">
      <thead><tr><th scope="col">Chart</th><th scope="col">Verdict</th><th scope="col">Assessment</th><th scope="col"><span class="sr">Preview</span></th></tr></thead>
      <tbody>${ok
        .map((s) => `<tr data-to="${s.to}" data-verdict="${s.verdict}"><td><a href="#c-${s.to}"><code>${s.to}</code></a></td><td><span class="verdict v-${s.verdict}">${MARK[s.verdict ?? "worse"]} ${VERDICT_WORDS[s.verdict ?? "worse"]}</span>${s.fit === "stretch" ? '<br><span class="muted">stretch</span>' : ""}</td><td class="assess">${escape(s.assessment)}${s.caveats.length ? `<br><span class="muted">${escape(s.caveats.join(" "))}</span>` : ""}</td><td><button type="button" data-from="${type}" data-to="${s.to}">Show</button></td></tr>`)
        .join("")}</tbody>
    </table></div>
    ${no.length ? `<details class="nope"><summary>Not possible with this data (${no.length})</summary><ul>${no.map((s) => `<li><code>${s.to}</code>: ${escape(s.caveats[0] ?? s.assessment)}</li>`).join("")}</ul></details>` : ""}
  </section>`;
};
const sections = charts.map(section).join("\n");

