const SETS: Record<Lang, Words> = { en: EN, fr: FR, de: DE };

/** Something that knows its locale: a locale string, a spec, or a view's context. */
export type LocaleSource = string | null | undefined | { locale?: string } | { spec: { locale?: string } };

/** The words for a locale, a spec or a view's context: French for "fr-…", German for "de-…", English otherwise. */
export function wordsFor(source?: LocaleSource): Words {
  const locale =
    typeof source === "string" || source === null || source === undefined
      ? source
      : "spec" in source
        ? source.spec?.locale
        : (source as { locale?: string }).locale;
  return SETS[langOf(locale)];
}

/** The English set: what every locale falls back to. */
export const WORDS_EN: Words = EN;
